"""Narrow interfaces used by workflows and simulation implementations."""

from __future__ import annotations

from typing import Protocol

from domain.models import VisionResult


class GantryController(Protocol):
    """Text-command Gantry Nano endpoint."""

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def send(self, command: str) -> None: ...


class HydroponicsController(Protocol):
    """Text-command Hydroponics Nano endpoint."""

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def send(self, command: str) -> None: ...


class ArmController(Protocol):
    """Write-only robotic-arm action-group endpoint."""

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def run_group(self, group_id: int, repeat_count: int = 1) -> None: ...
    def stop_group(self) -> None: ...


class VisionService(Protocol):
    """Camera/model or mock plant-classification endpoint."""

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def capture(self, plant: int) -> VisionResult: ...
